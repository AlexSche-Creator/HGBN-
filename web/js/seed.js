// Строки, выделенные в бумажной таблице.
const HIGHLIGHTED = new Set([19, 30, 51]);

export const SEED_COUNT = ROWS.length;

export function seedInterventions(store) {
  let added = 0, skipped = 0;
  const now = new Date().toISOString();
  ROWS.forEach(([n, name, type, clinic, year, phys, psych, neuro, sensations]) => {
    // Дедупликация по номеру строки бумажной таблицы: повторный запуск ничего
    // не задвоит, но и не схлопнет законные повторы (Амитриптилин 2019 из двух
    // клиник; Галидор дважды в 2021 в одной клинике — это разные строки).
    const dup = store.medications().some((m) => m.seedNo === n);
    if (dup) { skipped++; return; }
    store.upsertMedication({
      id: store.uid(), name, type, medClass: 'other',
      doseValue: '', doseUnit: '', schedule: '',
      prescribedBy: '', prescribedDate: '', purpose: '',
      clinic, year,
      physScore: phys, psychScore: psych, neuroScore: neuro,
      sensations: sensations || '',
      highlighted: HIGHLIGHTED.has(n),
      isActive: false, startDate: '', endDate: '',
      notes: '', sortOrder: n, seedNo: n, source: 'paper-table', createdAt: now,
    });
    added++;
  });
  return { added, skipped };
}
